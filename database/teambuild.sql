-- ============================================================

CREATE DATABASE IF NOT EXISTS teambuild
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE teambuild;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS equipe_pokemon, equipes, pokemon_tipos, pokemon, tipos, usuarios;
SET FOREIGN_KEY_CHECKS = 1;

-- Usuários do site. A senha nunca é guardada pura, só o hash (password_hash do PHP).
CREATE TABLE usuarios (
  id          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  nome        VARCHAR(80)  NOT NULL,
  email       VARCHAR(160) NOT NULL,
  senha_hash  VARCHAR(255) NOT NULL,
  papel       ENUM('usuario', 'admin') NOT NULL DEFAULT 'usuario',
  criado_em   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_usuarios_email (email)
) ENGINE=InnoDB;

-- Os 15 tipos existentes na 1ª geração. O "slug" é usado nas classes de cor do CSS.
CREATE TABLE tipos (
  id    TINYINT UNSIGNED NOT NULL AUTO_INCREMENT,
  slug  VARCHAR(20) NOT NULL,
  nome  VARCHAR(30) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_tipos_slug (slug)
) ENGINE=InnoDB;

-- Catálogo da Pokédex.
CREATE TABLE pokemon (
  id          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  numero      SMALLINT UNSIGNED NOT NULL,
  nome        VARCHAR(60)  NOT NULL,
  imagem_url  VARCHAR(255) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_pokemon_numero (numero),
  UNIQUE KEY uq_pokemon_nome (nome)
) ENGINE=InnoDB;

-- Liga Pokémon e tipos (um Pokémon tem 1 ou 2 tipos). "ordem" 1 = tipo principal.
CREATE TABLE pokemon_tipos (
  pokemon_id  INT UNSIGNED NOT NULL,
  tipo_id     TINYINT UNSIGNED NOT NULL,
  ordem       TINYINT UNSIGNED NOT NULL,
  PRIMARY KEY (pokemon_id, tipo_id),
  CONSTRAINT fk_pt_pokemon FOREIGN KEY (pokemon_id) REFERENCES pokemon (id) ON DELETE CASCADE,
  CONSTRAINT fk_pt_tipo    FOREIGN KEY (tipo_id)    REFERENCES tipos (id)
) ENGINE=InnoDB;

-- Equipes. Cada equipe pertence a um usuário; apagar o usuário apaga as equipes dele.
CREATE TABLE equipes (
  id             INT UNSIGNED NOT NULL AUTO_INCREMENT,
  usuario_id     INT UNSIGNED NOT NULL,
  nome           VARCHAR(60) NOT NULL,
  criado_em      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_equipes_usuario (usuario_id),
  CONSTRAINT fk_equipes_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- Pokémon de cada equipe. A "posicao" só aceita 1 a 6 e é parte da chave primária,
-- então o próprio banco impede uma equipe com mais de 6 Pokémon.
-- Um Pokémon só pode aparecer uma vez por equipe.
CREATE TABLE equipe_pokemon (
  equipe_id   INT UNSIGNED NOT NULL,
  posicao     TINYINT UNSIGNED NOT NULL,
  pokemon_id  INT UNSIGNED NOT NULL,
  PRIMARY KEY (equipe_id, posicao),
  UNIQUE KEY uq_equipe_pokemon (equipe_id, pokemon_id),
  CONSTRAINT ck_posicao CHECK (posicao BETWEEN 1 AND 6),
  CONSTRAINT fk_ep_equipe  FOREIGN KEY (equipe_id)  REFERENCES equipes (id) ON DELETE CASCADE,
  CONSTRAINT fk_ep_pokemon FOREIGN KEY (pokemon_id) REFERENCES pokemon (id) ON DELETE RESTRICT
) ENGINE=InnoDB;

